#2. Скрипт который проверяет число на положительность отрицательность или равенство нулю
#3. Скрипт который проверяет существование директории и выводит сообщение пустая ли она или нет

#1. Принимаем имя файла
read -p "Введите название файла: " file_name
#2. Принимаем число
read -p "Введите число: " user_num
#3. Вводим название директории для проверки
read -p "Введите путь до директории: " dir_name


echo ""
#1. Проверка имени файла
if [ -f "$file_name" -a -r "$file_name" ]; then
	echo "$(ls -l "$file_name" | awk '{print $1, $5}')B"
else
	echo "Ошибка такого файла нет"
fi

echo ""
#2. Проверка числа
if [ "$user_num" -eq 0 ]; then

	echo "Число $user_num равно нулю"
elif [ "$user_num" -gt 0 ]; then
	echo "Число $user_num больше нуля"
elif [ "$user_num" -lt 0 ]; then
	echo "Число $user_num меньше нуля"
=======
