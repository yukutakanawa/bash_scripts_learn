	echo "Число больше нуля"
elif [ "$user_num" -lt 0 ]; then
	echo "Число меньше нуля"

else
	echo "Не число"
fi


echo ""
#3. Проверка директории
if [ -d "$dir_name" ]; then
	#Проверяем пуста ли директория
	if [ -z "$(ls -A "$dir_name" 2>/dev/null)" ]; then
		echo "Директория пуста"
	else
